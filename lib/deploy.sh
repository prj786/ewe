#!/usr/bin/env bash
# lib/deploy.sh — symlink dotfiles into ~/.config with timestamped backups.
#
# Why a symlink farm and not `cp`: re-runnable (re-linking is a no-op), trivial
# to see what's managed (`ls -l ~/.config/hypr` shows the repo target), and
# clean to remove (uninstall just unlinks + restores the backup). Why not GNU
# stow: it isn't installed on a minimal base and its tree-folding surprises on
# configs that mix managed + user-written files (our generated/user.lua etc.).

# BACKUP_DIR is stamped once per run (timestamp passed in from install.sh so a
# --dry-run and a real run don't drift, and resume is deterministic).
backup_path() { printf '%s/%s.bak.%s' "$(dirname "$1")" "$(basename "$1")" "$RUN_STAMP"; }

# link_tree <src-dir> <dest-dir> — symlink dest-dir -> src-dir, backing up any
# pre-existing real dir/file/link at dest first.
link_tree() {
    local src="$1" dest="$2"
    [ -d "$src" ] || { warn "payload missing: $src"; return 1; }
    run mkdir -p "$(dirname "$dest")"
    if [ -L "$dest" ]; then
        local cur; cur="$(readlink -f "$dest" 2>/dev/null)"
        if [ "$cur" = "$(readlink -f "$src")" ]; then ok "already linked: $dest"; return 0; fi
        info "replacing stale symlink: $dest"
        run rm -f "$dest"
    elif [ -e "$dest" ]; then
        local bak; bak="$(backup_path "$dest")"
        info "backing up existing $dest -> $bak"
        run mv "$dest" "$bak"
    fi
    run ln -s "$src" "$dest"
    ok "linked $dest -> $src"
}

# seed_state — populate gitignored user-state files from their .default template
# only when absent, so a fresh clone has working defaults and re-runs never
# clobber the user's own theme/pins/overrides.
seed_state() {
    local f
    for f in "$DOTREPO/dotfiles/quickshell/user-theme.json" \
             "$DOTREPO/dotfiles/quickshell/pinned-apps.json" \
             "$DOTREPO/dotfiles/quickshell/places.json" \
             "$DOTREPO/dotfiles/quickshell/startup-apps.json" \
             "$DOTREPO/dotfiles/hypr/generated/user.lua"; do
        [ -e "$f" ] && continue
        [ -e "$f.default" ] || continue
        run cp "$f.default" "$f"
        ok "seeded $(basename "$f") from default"
    done
}

deploy_dotfiles() {
    seed_state
    link_tree "$DOTREPO/dotfiles/hypr"       "$HOME/.config/hypr"
    link_tree "$DOTREPO/dotfiles/quickshell" "$HOME/.config/quickshell"
    # dev environment: Zed, kitty, oh-my-posh, mise (themed to the DE palette)
    link_tree "$DOTREPO/dotfiles/zed"        "$HOME/.config/zed"
    link_tree "$DOTREPO/dotfiles/kitty"      "$HOME/.config/kitty"
    link_tree "$DOTREPO/dotfiles/oh-my-posh" "$HOME/.config/oh-my-posh"
    link_tree "$DOTREPO/dotfiles/mise"       "$HOME/.config/mise"
    # the shared shell config (zsh + bash + aliases + the rc-wiring script) and
    # the system-info fetch's configs (fastfetch, wearing the ewe logo)
    link_tree "$DOTREPO/dotfiles/shell"      "$HOME/.config/ewe-shell"
    link_tree "$DOTREPO/dotfiles/fastfetch"  "$HOME/.config/fastfetch"
    # default apps, themed to the flock palette (zathura's accent colours are
    # generated by colorscheme.sh into the linked dir — gitignored)
    link_tree "$DOTREPO/dotfiles/zathura"    "$HOME/.config/zathura"
    link_tree "$DOTREPO/dotfiles/fontconfig" "$HOME/.config/fontconfig"
    link_tree "$DOTREPO/dotfiles/imv"        "$HOME/.config/imv"
    link_tree "$DOTREPO/dotfiles/mpv"        "$HOME/.config/mpv"

    # systemd user units (portal-activation target + the shell respawn service)
    # are copied, not symlinked — systemd resolves symlinks oddly for unit files
    # and `daemon-reload` is cheap.
    run mkdir -p "$HOME/.config/systemd/user"
    run cp -f "$DOTREPO/systemd/hyprland-session.target" "$HOME/.config/systemd/user/"
    run cp -f "$DOTREPO/systemd/ewe.service"      "$HOME/.config/systemd/user/"
    # Remote (RFC-009): the per-user sshd behind "Share this computer" —
    # installed, never enabled here; `ewe-remote share on` enables it
    run cp -f "$DOTREPO/systemd/ewe-remote-sshd.service" "$HOME/.config/systemd/user/"
    # migrate: the unit was called hypr-shell.service before the ewe rename —
    # a stale copy would keep a second shell respawn loop alive
    if [ -f "$HOME/.config/systemd/user/hypr-shell.service" ]; then
        run systemctl --user disable --now hypr-shell.service 2>/dev/null || true
        run rm -f "$HOME/.config/systemd/user/hypr-shell.service"
    fi
    run systemctl --user daemon-reload 2>/dev/null || true
    ok "installed hyprland-session.target + ewe.service (shell respawn) + ewe-remote-sshd.service"
    deploy_portal
}

# The file picker (RFC-011). xdg-desktop-portal reads the user's routing
# (~/.config/xdg-desktop-portal) and portal files (~/.local/share/
# xdg-desktop-portal/portals) before the system's (checked on x-d-p 1.22), and
# the session bus reads ~/.local/share/dbus-1/services — so the whole backend
# deploys per user, without root, on both install paths (phase 50 and
# ewe-setup both run deploy_dotfiles).
deploy_portal() {
    local was_ours=0 cfg="$HOME/.config/xdg-desktop-portal"
    if [ -L "$cfg" ] && [ "$(readlink -f "$cfg")" = "$(readlink -f "$DOTREPO/dotfiles/xdg-desktop-portal")" ]; then
        was_ours=1
    fi
    link_tree "$DOTREPO/dotfiles/xdg-desktop-portal" "$cfg"
    run install -Dm644 "$DOTREPO/system/portal/ewe.portal" \
        "$HOME/.local/share/xdg-desktop-portal/portals/ewe.portal"
    run install -Dm644 "$DOTREPO/system/portal/org.freedesktop.impl.portal.desktop.ewe.service" \
        "$HOME/.local/share/dbus-1/services/org.freedesktop.impl.portal.desktop.ewe.service"
    run mkdir -p "$HOME/.local/bin"
    run ln -sfn "$DOTREPO/bin/ewe-portal" "$HOME/.local/bin/ewe-portal"
    run cp -f "$DOTREPO/systemd/ewe-portal.service" "$HOME/.config/systemd/user/"
    run systemctl --user daemon-reload 2>/dev/null || true
    # the bus picks up the new activation file; a running backend restarts on
    # the new code (it is started again on the next file dialog)
    run busctl --user call org.freedesktop.DBus /org/freedesktop/DBus org.freedesktop.DBus ReloadConfig 2>/dev/null || true
    run systemctl --user try-restart ewe-portal.service 2>/dev/null || true
    # the frontend reads its routing once, at start: restart it the first time
    # only (a restart ends any screen share in progress)
    if [ "$was_ours" = 0 ]; then
        run systemctl --user try-restart xdg-desktop-portal.service 2>/dev/null || true
    fi
    ok "installed ewe-portal (the file picker for every app)"
}
